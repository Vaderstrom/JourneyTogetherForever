-- Other languages: a file Locales/<code>.lua (listed in the TOC after this one) calls
--   ns.AddLocale("sv", { ADDON_NAME = "...", ... })
-- with only the texts it translates; the rest stay English. Settings → Language picks one (after a /reload).
ns.LOCALES = {}
function ns.AddLocale(code, strings) ns.LOCALES[code] = strings end
function ns.UseLocale(code)
  local strings = ns.LOCALES[code]
  if not strings then return false end
  for k, v in pairs(strings) do if type(v) == "string" then rawset(ns.L, k, v) end end
  return true
end
